-- HenSense shared Web + Mobile profile photos.
-- Run ONCE in Supabase Dashboard > SQL Editor as a project administrator.
-- This creates a PRIVATE bucket; do not make profile photos publicly accessible.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('hensense-avatars', 'hensense-avatars', false, 2097152,
        array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set
  public = false,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Restrict every object to its authenticated owner's UUID directory: <auth.uid()>/<filename>.
-- Filename is generated by the apps; a user cannot read another user's profile photo.
drop policy if exists "hensense_avatar_select_own" on storage.objects;
create policy "hensense_avatar_select_own" on storage.objects
for select to authenticated
using (bucket_id = 'hensense-avatars'
       and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "hensense_avatar_insert_own" on storage.objects;
create policy "hensense_avatar_insert_own" on storage.objects
for insert to authenticated
with check (bucket_id = 'hensense-avatars'
            and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "hensense_avatar_delete_own" on storage.objects;
create policy "hensense_avatar_delete_own" on storage.objects
for delete to authenticated
using (bucket_id = 'hensense-avatars'
       and (storage.foldername(name))[1] = (select auth.uid())::text);
